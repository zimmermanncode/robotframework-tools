"""Smoke test: a robottools test library runs on the installed Robot Framework (7.x).

Covers keyword generation with `testlibrary` and the session keywords generated by
`SessionHandler`.
"""

from textwrap import dedent

import robot
from robot.api import ExecutionResult

LIBRARY = '''
from robottools import SessionHandler, testlibrary


class Connection(SessionHandler):
    def open(self, host, user="", secure=True):
        return {"host": host, "user": user, "secure": secure}


TestLibrary = testlibrary(session_handlers=[Connection])


class SmokeLibrary(TestLibrary):
    @TestLibrary.keyword
    def add_numbers(self, a, b):
        return int(a) + int(b)

    @TestLibrary.keyword
    def current_host(self):
        return self.connection["host"]

    @TestLibrary.keyword
    def current_connection(self):
        return self.connection
'''

SUITE = '''
*** Settings ***
Library    SmokeLibrary.py

*** Test Cases ***
Keyword
    ${sum}=    Add Numbers    2    3
    Should Be Equal As Integers    ${sum}    5

Sessions
    Open Named Connection    first    host-a
    Open Named Connection    second    host-b
    ${host}=    Current Host
    Should Be Equal    ${host}    host-b
    Switch Connection    first
    ${host}=    Current Host
    Should Be Equal    ${host}    host-a
    Close Connection
    Run Keyword And Expect Error    *    Current Host

Named Arguments
    Open Connection    host-c    secure=False
    ${connection}=    Current Connection
    Should Be Equal    ${connection}[user]    ${EMPTY}
    Should Be Equal    ${connection}[secure]    False
'''


def test_library_and_sessions_run_on_robot_framework(tmp_path):
    (tmp_path / "SmokeLibrary.py").write_text(dedent(LIBRARY), encoding="utf-8")
    (tmp_path / "smoke.robot").write_text(dedent(SUITE), encoding="utf-8")
    output = tmp_path / "output.xml"

    rc = robot.run(
        tmp_path / "smoke.robot", pythonpath=[str(tmp_path)], output=str(output),
        report=None, log=None, console="none",
    )

    result = ExecutionResult(str(output))
    failed = {test.name: test.message for test in result.suite.all_tests if not test.passed}
    errors = [message.message for message in result.errors.messages]
    assert (rc, failed, errors) == (0, {}, [])
